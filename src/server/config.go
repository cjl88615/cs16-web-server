package main

import (
 "fmt"
 "net"
 "os"
 "path/filepath"
 "regexp"
 "strconv"
 "strings"
)
const releaseVersion = "2026.11.07-r1"
type GameConfig struct {
 Version string `json:"version"`
 Name string `json:"name"`
 Map string `json:"map"`
 MaxPlayers int `json:"maxPlayers"`
 BotQuota int `json:"botQuota"`
 BotDifficulty int `json:"botDifficulty"`
 IP string `json:"-"`
 Port int `json:"-"`
}
var gameConfig GameConfig
var mapNamePattern = regexp.MustCompile(`^[a-zA-Z0-9_]{1,48}$`)
func envValue(key, fallback string) string {
 if value := os.Getenv(key); value != "" { return value }
 return fallback
}
func envInt(key string, fallback, low, high int) (int, error) {
 value, err := strconv.Atoi(envValue(key, strconv.Itoa(fallback)))
 if err != nil || value < low || value > high { return 0, fmt.Errorf("%s must be an integer between %d and %d", key, low, high) }
 return value, nil
}
func loadGameConfig() (GameConfig, error) {
 cfg := GameConfig{Version: releaseVersion, Name: envValue("SERVER_NAME", "Taliabu CS 1.6"), Map: envValue("START_MAP", "de_dust2"), IP: envValue("LAN_IP", os.Getenv("IP"))}
 if !mapNamePattern.MatchString(cfg.Map) { return cfg, fmt.Errorf("START_MAP contains invalid characters") }
 if len(cfg.Name) > 80 || strings.ContainsAny(cfg.Name, "\"\\;\r\n\x00") { return cfg, fmt.Errorf("SERVER_NAME contains invalid characters or is too long") }
 ip := net.ParseIP(cfg.IP)
 if ip == nil || ip.To4() == nil || ip.IsUnspecified() || ip.IsLoopback() || ip.IsMulticast() { return cfg, fmt.Errorf("LAN_IP must be the real, non-loopback IPv4 address reachable by players") }
 var err error
 if cfg.MaxPlayers, err = envInt("MAX_PLAYERS", 16, 2, 32); err != nil { return cfg, err }
 if cfg.BotQuota, err = envInt("BOT_QUOTA", 8, 0, cfg.MaxPlayers-1); err != nil { return cfg, err }
 if cfg.BotDifficulty, err = envInt("BOT_DIFFICULTY", 2, 0, 4); err != nil { return cfg, err }
 if cfg.Port, err = envInt("PORT", 27018, 1024, 65535); err != nil { return cfg, err }
 return cfg, nil
}
// Prepare only our generated settings. User-supplied server.cfg remains intact.
func prepareGame(root string, cfg GameConfig) error {
 game := filepath.Join(root, "cstrike")
 for _, file := range []string{"maps/"+cfg.Map+".bsp", "dlls/cs.so", "addons/yapb/bin/yapb.so", "addons/yapb/data/graph/"+cfg.Map+".graph"} {
  if _, err := os.Stat(filepath.Join(game, file)); err != nil { return fmt.Errorf("required game/BOT file missing: %s: %w", file, err) }
 }
 for _, filename := range []string{"liblist.gam", "gameinfo.txt"} {
  path := filepath.Join(game, filename)
  data, err := os.ReadFile(path)
  if os.IsNotExist(err) && filename == "gameinfo.txt" { continue }
  if err != nil { return err }
  expression := regexp.MustCompile(`(?m)^\s*"?gamedll_linux"?\s+[^\r\n]*`)
  line := `gamedll_linux "addons/yapb/bin/yapb.so"`
  text := expression.ReplaceAllString(string(data), line)
  if !expression.Match(data) { text += "\n" + line + "\n" }
  if err := os.WriteFile(path, []byte(text), 0644); err != nil { return err }
 }
 bots := fmt.Sprintf(`// Generated by %s; edit .env, not this file.
yb_quota_mode "fill"
yb_quota "%d"
yb_difficulty "%d"
yb_autovacate "1"
yb_autovacate_keep_slots "1"
yb_join_after_player "1"
yb_display_welcome_text "0"
yb_graph_auto_collect_db "0"
yb_graph_analyze_auto_start "0"
yb_graph_url ""
yb_graph_url_upload ""
yb_chat "0"
`, releaseVersion, cfg.BotQuota, cfg.BotDifficulty)
 if err := os.WriteFile(filepath.Join(game, "addons/yapb/conf/yapb.cfg"), []byte(bots), 0644); err != nil { return err }
 settings := fmt.Sprintf("// Generated settings\nhostname \"%s\"\nexec addons/yapb/conf/yapb.cfg\n", cfg.Name)
 return os.WriteFile(filepath.Join(game, "lan-game.cfg"), []byte(settings), 0644)
}
